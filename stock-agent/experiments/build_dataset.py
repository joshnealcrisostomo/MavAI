"""Build the forecast-vetting dataset.

For each event (see events.py) we call tools.vet_forecast to assemble the matched triplet:
  - the price-only forecast (made as-of the event, no lookahead)
  - the news that existed BEFORE the event (Finnhub, cached)
  - the actual outcome over the next `horizon` trading days
and persist the whole bundle. This is generated by the code, not collected by hand - the only hand
step is choosing/annotating the events. Output: experiments/results/forecast_dataset.json.

Run from the project root:
    ./.venv/Scripts/python.exe experiments/build_dataset.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))

from core import tools  # noqa: E402
import events  # noqa: E402

OUT = ROOT / "experiments" / "results" / "forecast_dataset.json"


def build() -> list[dict]:
    evs = events.get_events()
    dataset = []
    for e in evs:
        b = tools.run_tool("vet_forecast", {"ticker": e["ticker"], "as_of_date": e["event_date"]})
        ok = b.get("ok")
        n_news = len(b.get("news_before", [])) if ok else 0
        act = b.get("actual", {}).get("direction") if ok else None
        fdir = b.get("forecast", {}).get("direction") if ok else None
        print(f"{e['ticker']:5} {e['event_date']}  ok={ok}  forecast={fdir}  actual={act}  news={n_news}"
              + ("" if ok else f"  ERR {b.get('error')}"))
        dataset.append({"event": e, "bundle": b})
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(dataset, indent=2), encoding="utf-8")
    print(f"\nwrote {OUT}  ({len(dataset)} events)")
    return dataset


if __name__ == "__main__":
    build()
